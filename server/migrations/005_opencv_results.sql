CREATE TABLE opencv_results (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id NUMBER NOT NULL,
  user_id NUMBER NOT NULL,
  job_id NUMBER NOT NULL,
  coordinate_space VARCHAR2(32) NOT NULL,
  candidate_geometry_json CLOB NOT NULL,
  confidence NUMBER(5, 4),
  algorithm VARCHAR2(100) DEFAULT 'opencv-js-canny-hough-v1' NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_opencv_results_project_id
    FOREIGN KEY (project_id) REFERENCES room_projects(id),
  CONSTRAINT fk_opencv_results_user_id
    FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_opencv_results_job_id
    FOREIGN KEY (job_id) REFERENCES reconstruction_jobs(id),
  CONSTRAINT chk_opencv_results_coordinate_space
    CHECK (coordinate_space IN ('image_pixels')),
  CONSTRAINT chk_opencv_results_confidence
    CHECK (confidence IS NULL OR (confidence >= 0 AND confidence <= 1))
);

CREATE INDEX idx_opencv_results_job_id ON opencv_results(job_id);
CREATE INDEX idx_opencv_results_user_project ON opencv_results(user_id, project_id);
